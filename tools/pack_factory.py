"""Pack 32 presets per independently decodable block with data grouped by field."""
import json
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root / "base/tools"))
from lz4blk import compress, decompress

def body(file, symbol):
    return re.search(rf"\b{symbol}\b[^=]*=\s*\{{(.*?)\}};", (root / file).read_text(), re.S)[1]

def values(file, symbol):
    return bytes(map(int, re.findall(r"\d+", body(file, symbol))))

model = sys.argv[1]
params = values("engine/presets.inc", "preset_params")
routes = values("engine/matrix.inc", "matrix_factory")
banks = values("engine/presets.inc", "preset_banks")
programs = values("engine/presets.inc", "preset_programs")
flags = values("runtime/preset_status.inc", "preset_status_flags")
names = json.loads("[" + body("engine/presets.inc", "preset_names") + "]")
count = len(banks)
bank_count = max(banks) + 1
bank_labels = [f"{m}-{chr(65 + i)}" for m in ("ABC" if model == "ALL" else model)
               for i in range(2 if m == "A" else 6)]
assert len(bank_labels) == bank_count
assert count == len(names) == len(flags) == len(programs)
assert len(params) == count * 126 and len(routes) == count * 33
assert banks == bytes(sorted(banks))
starts = [banks.index(i) for i in range(bank_count)] + [count]
for lo, hi in zip(starts, starts[1:]):
    assert list(programs[lo:hi]) == sorted(set(programs[lo:hi]))
rows = [params[i*126:(i+1)*126] + routes[i*33:(i+1)*33]
        for i in range(count)]
offsets = [0]
blob = bytearray()
for i in range(0, count, 32):
    batch = rows[i:i+32]
    raw = b"".join(bytes(col) for col in zip(*batch))
    packed = compress(raw)
    restored = decompress(packed)
    assert [restored[j::len(batch)] for j in range(len(batch))] == batch
    blob.extend(packed)
    offsets.append(len(blob))

def array(kind, name, data):
    lines = [",".join(map(str, data[i:i+24])) for i in range(0, len(data), 24)]
    return f"static const {kind} {name}[]={{\n" + ",\n".join(lines) + "\n};\n"

output = f"/* Generated by tools/pack_factory.py */\n#define VC_PRESET_COUNT {count}u\n"
output += f"#define VC_PRESET_BANK_COUNT {bank_count}u\n"
output += array("uint32_t", "packed_offsets", offsets)
output += array("uint8_t", "packed_presets", blob)
output += array("uint16_t", "bank_first", starts)
output += array("uint8_t", "preset_banks", banks)
output += array("uint8_t", "preset_programs", programs)
output += array("uint8_t", "preset_status", flags)
output += "static const char preset_names[][11]={" + ",".join(map(json.dumps, names)) + "};\n"
output += "static const char bank_labels[][4]={" + ",".join(map(json.dumps, bank_labels)) + "};\n"
(root / "engine/packed_presets.inc").write_text(output)
print(f"Verified {count} presets in {bank_count} banks, {len(blob)} compressed parameter bytes")
