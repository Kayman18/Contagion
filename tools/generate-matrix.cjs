const fs=require('fs'),path=require('path');
const root=path.join(__dirname,'..'),ref=require('./reference.cjs');
const presets=JSON.parse(fs.readFileSync(path.join(root,'presets/factory-decoded.json')));
if(ref.matrixDestinations.length!==123)throw Error('Destination count changed');
function routes(p){return ref.matrixSlots.flatMap(([s,...pairs])=>pairs.map(([d,a])=>[p[s],p[d],p[a]]))
  .concat(ref.matrixLfos.map(([s,d,a])=>[s,p[d],p[a]]));}
const rows=presets.map(p=>{
 if(p.patch.arpMode)throw Error('Arpeggiated preset in retained bank');
 return '{{'+routes(p.patch).map(r=>'{'+r.join(',')+'}').join(',')+'}}';
});
fs.writeFileSync(path.join(root,'engine/matrix.inc'),
 '// Generated by tools/generate-matrix.cjs; original destination IDs.\n'+
 'static const uint8_t matrix_destination_active[VC_MATRIX_DESTINATIONS]={'+ref.matrixDestinations.map(d=>d[1]?1:0).join(',')+'};\n'+
 'static const VCMatrix matrix_factory[]={\n'+rows.join(',\n')+'\n};\n');
console.log(JSON.stringify({presets:presets.length,routesPerPreset:11,routeBytes:presets.length*33}));
