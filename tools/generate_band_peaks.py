"""Bind exact prototype normalization peaks to the captured compressed bank."""
from pathlib import Path
import struct,zlib
root=Path(__file__).resolve().parents[1]
peaks=(root/'experimental/wave-peaks.f32').read_bytes()
assert len(peaks)==256
bank=(root/'data/VIROOOS-WAV.bin').read_bytes()
text='/* Generated by tools/generate_band_peaks.py; rerun band reconstruction test first. */\n'
text+=f'#define VC_BAND_BANK_BYTES {len(bank)}u\n#define VC_BAND_BANK_CRC 0x{zlib.crc32(bank):08x}u\n'
text+='static const float vc_band_peaks[64]={\n'+','.join(float(x).hex()+'f' for x in struct.unpack('<64f',peaks))+'\n};\n'
(root/'experimental/band_peaks.inc').write_text(text)
